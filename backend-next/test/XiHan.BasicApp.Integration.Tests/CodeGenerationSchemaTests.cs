namespace XiHan.BasicApp.Integration.Tests;

/// <summary>
/// 验证代码生成在真实的外部库上读库结构与推断类型。
/// </summary>
/// <remarks>
/// PostgreSQL、MySQL、SQL Server、Oracle 各建一个临时库（环境变量见 <see cref="ExternalDatabase"/>，没设即跳过），经数据源测试连接、列出库表、导入，
/// 核对框架读库结构的口径（修订（八十三））：长度只给字符与二进制类型，类型按各库的类型名映射（Oracle 的 <c>NUMBER</c> 按精度分整数与定点数、<c>DATE</c> 带时分秒，
/// SQL Server 的 <c>rowversion</c> 是二进制），表与列的注释读得到，大小写混合的表名照原样、自增读得到，零代码运行时按数据源读得到它的行。
/// </remarks>
public sealed class CodeGenerationSchemaTests : IDisposable
{
    private const string Admin = "codegen-admin";

    private readonly SqliteDatabase _database = new();

    public void Dispose() => _database.Dispose();

    /// <summary>
    /// 各库建演示表的语句与期望的 C# 类型。
    /// </summary>
    private static (string[] Statements, string MixedCase, Dictionary<string, string> Types) Fixture(string databaseType) => databaseType switch
    {
        "PostgreSql" => (
            [
                "CREATE TABLE \"demo_item\" (\"id\" uuid NOT NULL PRIMARY KEY, \"item_code\" varchar(50) NOT NULL, \"price\" numeric(18,2) NULL, \"qty\" integer NOT NULL, \"big_no\" bigint NULL, \"on_sale\" boolean NOT NULL, \"created_at\" timestamptz NOT NULL, \"released_on\" date NULL, \"note\" text NULL, \"payload\" bytea NULL)",
                "COMMENT ON TABLE \"demo_item\" IS '演示商品'",
                "COMMENT ON COLUMN \"demo_item\".\"item_code\" IS '商品编码'",
                "CREATE TABLE \"MixedCase\" (\"Id\" serial PRIMARY KEY, \"Name\" varchar(20) NULL)",
            ],
            "MixedCase",
            new() { ["id"] = "Guid", ["item_code"] = "string", ["price"] = "decimal?", ["qty"] = "int", ["big_no"] = "long?", ["on_sale"] = "bool", ["created_at"] = "DateTimeOffset", ["released_on"] = "DateTimeOffset?", ["note"] = "string?", ["payload"] = "byte[]?" }),
        "MySql" => (
            [
                "CREATE TABLE demo_item (id CHAR(36) NOT NULL PRIMARY KEY, item_code VARCHAR(50) NOT NULL COMMENT '商品编码', price DECIMAL(18,2) NULL, qty INT NOT NULL, big_no BIGINT NULL, on_sale BIT(1) NOT NULL, created_at DATETIME(6) NOT NULL, released_on DATE NULL, note LONGTEXT NULL, payload BLOB NULL) COMMENT='演示商品'",
                "CREATE TABLE MixedCase (Id INT AUTO_INCREMENT PRIMARY KEY, Name VARCHAR(20) NULL)",
            ],
            "MixedCase",
            new() { ["id"] = "string", ["item_code"] = "string", ["price"] = "decimal?", ["qty"] = "int", ["big_no"] = "long?", ["on_sale"] = "bool", ["created_at"] = "DateTimeOffset", ["released_on"] = "DateTimeOffset?", ["note"] = "string?", ["payload"] = "byte[]?" }),
        "SqlServer" => (
            [
                "CREATE TABLE demo_item (id UNIQUEIDENTIFIER NOT NULL PRIMARY KEY, item_code NVARCHAR(50) NOT NULL, price DECIMAL(18,2) NULL, qty INT NOT NULL, big_no BIGINT NULL, on_sale BIT NOT NULL, created_at DATETIMEOFFSET NOT NULL, released_on DATE NULL, note NVARCHAR(MAX) NULL, payload VARBINARY(MAX) NULL, row_ver ROWVERSION NOT NULL)",
                "EXEC sp_addextendedproperty N'MS_Description', N'演示商品', N'SCHEMA', N'dbo', N'TABLE', N'demo_item'",
                "EXEC sp_addextendedproperty N'MS_Description', N'商品编码', N'SCHEMA', N'dbo', N'TABLE', N'demo_item', N'COLUMN', N'item_code'",
                "CREATE TABLE MixedCase (Id INT IDENTITY(1,1) PRIMARY KEY, Name NVARCHAR(20) NULL)",
            ],
            "MixedCase",
            new() { ["id"] = "Guid", ["item_code"] = "string", ["price"] = "decimal?", ["qty"] = "int", ["big_no"] = "long?", ["on_sale"] = "bool", ["created_at"] = "DateTimeOffset", ["released_on"] = "DateTimeOffset?", ["note"] = "string?", ["payload"] = "byte[]?", ["row_ver"] = "byte[]" }),
        "Oracle" => (
            [
                "CREATE TABLE \"demo_item\" (\"id\" RAW(16) NOT NULL PRIMARY KEY, \"item_code\" VARCHAR2(50) NOT NULL, \"price\" NUMBER(18,2), \"qty\" NUMBER(9) NOT NULL, \"big_no\" NUMBER(18), \"created_at\" TIMESTAMP NOT NULL, \"released_on\" DATE, \"note\" CLOB, \"payload\" BLOB)",
                "COMMENT ON TABLE \"demo_item\" IS '演示商品'",
                "COMMENT ON COLUMN \"demo_item\".\"item_code\" IS '商品编码'",
                "CREATE TABLE \"MixedCase\" (\"Id\" NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, \"Name\" VARCHAR2(20))",
            ],
            "MixedCase",
            new() { ["id"] = "byte[]", ["item_code"] = "string", ["price"] = "decimal?", ["qty"] = "int", ["big_no"] = "long?", ["created_at"] = "DateTimeOffset", ["released_on"] = "DateTimeOffset?", ["note"] = "string?", ["payload"] = "byte[]?" }),
        _ => throw new ArgumentOutOfRangeException(nameof(databaseType)),
    };

    [Theory]
    [InlineData("PostgreSql")]
    [InlineData("MySql")]
    [InlineData("SqlServer")]
    [InlineData("Oracle")]
    public async Task ExternalDatabases_AreReadWithTheFrameworkValues(string databaseType)
    {
        await using var database = ExternalDatabase.Create(databaseType);
        var (statements, mixedCase, types) = Fixture(databaseType);
        database.Execute(statements);

        await using var server = await BasicAppTestServer.StartAsync(_database.ConnectionString);
        await server.SeedDefaultsAsync();
        await server.SeedAsync([], [.. CodeGenerationPermissions.All.Select(static p => new PermissionGrant(GrantSubject.ForRole(Admin), p.Code))]);
        var admin = TestTokens.Issue("root", null, Admin);

        var (created, source) = await server.SendAsync(BasicAppTestServer.Request(HttpMethod.Post, "/api/codegen-datasources", JsonSerializer.Serialize(new { sourceName = databaseType, databaseType = database.DatabaseType, host = "explicit", port = 0, databaseName = "explicit", userName = "explicit", connectionString = database.ConnectionString }), admin));
        Assert.Equal(HttpStatusCode.Created, created.StatusCode);
        var sourceId = source.GetProperty("id").GetString();
        var (_, tested) = await server.SendAsync(BasicAppTestServer.Request(HttpMethod.Post, $"/api/codegen-datasources/{sourceId}:test-connection", token: admin));
        Assert.True(tested.GetProperty("success").GetBoolean(), tested.GetProperty("message").GetString());

        // 列出库表：原名照样，注释读得到
        var (listed, tables) = await server.SendAsync(BasicAppTestServer.Request(HttpMethod.Post, "/api/codegen-tables:db-tables", JsonSerializer.Serialize(new { dataSourceId = sourceId, page = new { index = 1, size = 50 } }), admin));
        Assert.Equal(HttpStatusCode.OK, listed.StatusCode);
        var names = tables.GetProperty("items").EnumerateArray().ToDictionary(static t => t.GetProperty("name").GetString()!, static t => t.GetProperty("comment").GetString());
        Assert.Contains(mixedCase, names.Keys);
        Assert.Equal("演示商品", names["demo_item"]);

        var (imported, result) = await server.SendAsync(BasicAppTestServer.Request(HttpMethod.Post, "/api/codegen-tables:import", JsonSerializer.Serialize(new { dataSourceId = sourceId, tableNames = new[] { "demo_item", mixedCase } }), admin));
        Assert.Equal(HttpStatusCode.OK, imported.StatusCode);
        Assert.Equal(2, result.GetProperty("succeeded").GetArrayLength());

        var (_, list) = await server.SendAsync(BasicAppTestServer.Request(HttpMethod.Post, "/api/codegen-tables:list", """{"page":{"index":1,"size":50}}""", admin));
        var ids = list.GetProperty("items").EnumerateArray().ToDictionary(static t => t.GetProperty("tableName").GetString()!, static t => t.GetProperty("id").GetString());
        var (_, item) = await server.SendAsync(BasicAppTestServer.Request(HttpMethod.Get, $"/api/codegen-tables/{ids["demo_item"]}", token: admin));
        Assert.Equal(("DemoItem", "演示商品", databaseType), (item.GetProperty("table").GetProperty("className").GetString(), item.GetProperty("table").GetProperty("tableComment").GetString(), item.GetProperty("table").GetProperty("databaseType").GetString()));
        var columns = item.GetProperty("columns").EnumerateArray().ToDictionary(static c => c.GetProperty("columnName").GetString()!);
        foreach (var (column, type) in types)
        {
            Assert.True(columns.ContainsKey(column), $"{databaseType}: column {column} missing");
            Assert.Equal((column, type), (column, columns[column].GetProperty("cSharpType").GetString()));
        }

        // 长度只给字符类型；定点数给小数位
        Assert.Equal(50, columns["item_code"].GetProperty("columnLength").GetInt32());
        Assert.Equal(JsonValueKind.Null, columns["qty"].GetProperty("columnLength").ValueKind);
        Assert.Equal(2, columns["price"].GetProperty("decimalDigits").GetInt32());
        Assert.Equal("商品编码", columns["item_code"].GetProperty("columnComment").GetString());
        Assert.True(columns["id"].GetProperty("isPrimaryKey").GetBoolean());

        // 大小写混合的表名：原样导入，自增读得到
        var (_, mixed) = await server.SendAsync(BasicAppTestServer.Request(HttpMethod.Get, $"/api/codegen-tables/{ids[mixedCase]}", token: admin));
        var mixedColumns = mixed.GetProperty("columns").EnumerateArray().ToDictionary(static c => c.GetProperty("columnName").GetString()!);
        Assert.True(mixedColumns["Id"].GetProperty("isIdentity").GetBoolean());
        Assert.Equal(20, mixedColumns["Name"].GetProperty("columnLength").GetInt32());

        // 按表名同步结构回到同一个外部库
        var (synced, _) = await server.SendAsync(BasicAppTestServer.Request(HttpMethod.Post, $"/api/codegen-tables/{ids[mixedCase]}:sync-schema", token: admin));
        Assert.Equal(HttpStatusCode.OK, synced.StatusCode);

        // 零代码运行时按表配置的数据源读：大小写混合的表名照原样查到，键是属性名
        database.Execute(MixedCaseRow(databaseType));
        var (read, rows) = await server.SendAsync(BasicAppTestServer.Request(HttpMethod.Post, "/api/codegen-runtime:list", JsonSerializer.Serialize(new { id = ids[mixedCase], page = new { index = 1, size = 10 } }), admin));
        Assert.True(read.StatusCode == HttpStatusCode.OK, rows.ToString());
        Assert.Equal(1, rows.GetProperty("total").GetInt64());
        Assert.Equal("甲", rows.GetProperty("items")[0].GetProperty("name").GetString());
        Assert.Equal(1, rows.GetProperty("items")[0].GetProperty("id").GetInt32());
    }

    private static string MixedCaseRow(string databaseType) => databaseType switch
    {
        "PostgreSql" or "Oracle" => "INSERT INTO \"MixedCase\" (\"Name\") VALUES ('甲')",
        "SqlServer" => "INSERT INTO MixedCase (Name) VALUES (N'甲')",
        _ => "INSERT INTO MixedCase (Name) VALUES ('甲')",
    };
}
